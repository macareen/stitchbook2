package com.macareen.stitchbook2.ui.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Stitchbook's spacing scale. Prefer these over ad hoc `.dp` literals so
 * rhythm stays consistent across screens.
 */
object StitchbookSpacing {
    val extraSmall: Dp = 4.dp
    val small: Dp = 8.dp
    val medium: Dp = 16.dp
    val large: Dp = 24.dp
    val extraLarge: Dp = 32.dp
    val extraExtraLarge: Dp = 48.dp
}
